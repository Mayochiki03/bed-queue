/**
 * core/phone.ts — ช่องเบอร์โทรแบบยืดหยุ่น (เบอร์มือถือ / เบอร์สำนักงานที่มีเบอร์ต่อ เช่น "0243535646 ต่อ 1275")
 * เก็บเป็นข้อความตามที่พิมพ์ (ตัดช่องว่างซ้ำ) ไม่บังคับรูปแบบตายตัว แต่ต้องมีตัวเลขอย่างน้อย 8 หลัก
 * และใช้ได้เฉพาะ ตัวเลข ช่องว่าง - ( ) + , # / ต่อ ext
 */
import { z } from 'zod';


export const phoneText = (label = 'เบอร์โทร') =>
  z
    .string()
    .trim()
    .max(50, `${label}ยาวเกิน 50 ตัวอักษร`)
    .transform((s) => s.replace(/\s+/g, ' '))
    .refine((s) => s === '' || (s.replace(/\D/g, '').length >= 8 && /^[0-9\s\-()+,#/.ตต่อextEXT]+$/.test(s)), `${label}ไม่ถูกต้อง (ตัวเลขอย่างน้อย 8 หลัก ใส่ "ต่อ" เบอร์ภายในได้)`);

/** เบอร์หลัก (บังคับกรอก) */
export const phoneRequired = (label = 'เบอร์โทร') => phoneText(label).refine((s) => s !== '', `กรุณากรอก${label}`);
